import { expect, test } from '@playwright/test'
import { openApp } from './helpers'

test('phone: home shows recently opened pages, newest first (WS-05)', async ({ page }) => {
  await openApp(page)
  await page.getByRole('button', { name: '뒤로' }).click()
  await page.locator('.fab').tap()
  await page.waitForURL(/#\/w\/[^/]+\/v\//)
  await page.fill('.page-title', 'Recent X')
  await page.getByRole('button', { name: '뒤로' }).click()
  const recent = page.locator('.recent-card-title')
  await expect(recent).toHaveText(['Recent X', 'WebNota 시작하기'])
  await page.locator('.tree-link', { hasText: 'WebNota' }).tap()
  await page.getByRole('button', { name: '뒤로' }).click()
  await expect(recent).toHaveText(['WebNota 시작하기', 'Recent X'])
  await page.reload()
  await expect(recent).toHaveText(['WebNota 시작하기', 'Recent X'])
})

test('phone home: workspace switcher, settings shortcut, space tabs (MB-02)', async ({ page }) => {
  await openApp(page)
  await page.getByRole('button', { name: '뒤로' }).click()
  await expect(page.getByRole('button', { name: '워크스페이스 전환' })).toBeVisible()
  await page.getByRole('button', { name: '스페이스 전환', exact: true }).tap()
  await page.getByRole('menuitem', { name: '새 스페이스' }).tap()
  const dialog = page.getByRole('dialog', { name: '새 스페이스' })
  await dialog.getByLabel('이름').fill('Tab B')
  await dialog.getByRole('button', { name: '만들기' }).tap()
  const tabs = page.getByRole('navigation', { name: '스페이스' })
  await expect(tabs.getByRole('button')).toHaveCount(2)
  await expect(tabs.getByRole('button', { name: /Tab B/ })).toHaveAttribute('aria-pressed', 'true')
  await tabs.getByRole('button', { name: /일반/ }).tap()
  await expect(page.locator('.tree-title')).toHaveText(['WebNota 시작하기'])
  await page.getByRole('link', { name: '설정' }).first().tap()
  await expect(page.getByRole('heading', { name: '설정', exact: true, level: 1 })).toBeVisible()
})
